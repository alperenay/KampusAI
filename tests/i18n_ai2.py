def patch(path, d):
    s = open(path, encoding="utf-8").read()
    for k, v in d.items():
        line = "  " + json.dumps(k, ensure_ascii=False) + ": " + json.dumps(v, ensure_ascii=False)
        pat = re.compile(r'^  ' + re.escape(json.dumps(k, ensure_ascii=False)) + r': .*?(,?)$', re.M)
        m = pat.search(s)
        if m:
            s = s[:m.start()] + line + m.group(1) + s[m.end():]
        else:
            i = s.rindex("\n};")
            # ensure previous line ends with comma
            j = s.rstrip()[:-2].rstrip()
            s = s[:i].rstrip()
            if not s.endswith(","): s += ","
            s += "\n" + line + "\n};\n"
    open(path, "w", encoding="utf-8").write(s)
