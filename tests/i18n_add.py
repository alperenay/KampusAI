OLD_UNUSED = ["ai.soon","ai.mic","ai.modelInfo","ai.quickAddExam","ai.note","ai.notConnected","ai.tipExams","ai.tipSchedule","ai.tipTopics",
  "ai.error","ai.attachSoon","ai.micSoon","ai.modalTitle","ai.modalBody","ai.status","ai.connected","ai.notConnectedShort"]
NOTE = {"tr": "Yanıtlar bu bilgisayardaki modeller tarafından üretilir ve hata içerebilir; önemli bilgileri kontrol et.",
        "en": "Answers are generated by models on this computer and may contain mistakes; double-check important information."}
for lang, add in (("tr", TR), ("en", EN)):
    p = pathlib.Path(f"js/i18n/{lang}.js"); s = p.read_text()
    lines = s.split("\n")
    keep = []
    for ln in lines:
        st = ln.strip()
        if any(st.startswith(json.dumps(k) + ":") for k in OLD_UNUSED + list(add.keys())):
            continue
        keep.append(ln)
    s = "\n".join(keep)
    # son öğeden sonra ekle
    idx = s.rstrip().rfind("};")
    body = s[:idx].rstrip()
    if not body.endswith(","): body += ","
    block = "\n\n  /* Yerel yapay zeka (Ollama) */\n" + ",\n".join("  " + json.dumps(k, ensure_ascii=False) + ": " + json.dumps(v, ensure_ascii=False) for k, v in list(add.items()) + [("ai.note", NOTE[lang])])
    s = body + block + "\n};\n"
    p.write_text(s)
