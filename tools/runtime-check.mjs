import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const events=[],nodes=Object.fromEntries(['view','main','app','scrim'].map(id=>[id,{innerHTML:'',classList:{toggle(){},remove(){}},hidden:false}]));
const location={hash:'#/slow'},ctx=vm.createContext({App:{setTitle(){},hydrateIcons(){},ui:{empty:()=>'<error>'},t:s=>s},location,document:{getElementById:id=>nodes[id],querySelectorAll:()=>[]},window:{addEventListener(){},dispatchEvent:e=>events.push(e.detail.name)},CustomEvent:class{constructor(type,o){this.detail=o.detail;}},console:{error(){}},setTimeout,clearTimeout});
vm.runInContext(fs.readFileSync(path.join(root,'js/core/router.js'),'utf8'),ctx);
const R=ctx.App.router;let release,lateClean=0,fastClean=0;
R.register('slow',async()=>{await new Promise(r=>release=r);return()=>lateClean++;});
R.register('fast',v=>{v.innerHTML='fast';return()=>fastClean++;});R.register('last',v=>{v.innerHTML='last';});R.register('',v=>{v.innerHTML='home';});
const slow=R.refresh();location.hash='#/fast';await R.refresh();release();await slow;
assert.equal(lateClean,1,'A late async route must dispose its own resources');
assert.deepEqual(events,['fast'],'A stale route must not emit a successful navigation');
location.hash='#/last';await R.refresh();assert.equal(fastClean,1,'Current route cleanup must not be overwritten by an old completion');
let reject;
R.register('reject',async()=>{await new Promise((r,j)=>reject=j);});location.hash='#/reject';const pending=R.refresh();location.hash='#/fast';await R.refresh();reject(new Error('late error'));await pending;assert.equal(nodes.view.innerHTML,'fast','Late failure must not replace the current screen');
location.hash='#/%E0%A4%A';await R.refresh();assert.equal(nodes.view.innerHTML,'home','Malformed links must not crash navigation');
console.log('Runtime: stale completion, cleanup ownership, stale failure and malformed route checks passed.');
